def log(msg: str) -> None:
    print(f"[build] {msg}", flush=True)


def python_sha256() -> str:
    """The embeddable Python's SHA-256, checked against the pinned value (setup verifies its download with it)."""
    CACHE.mkdir(parents=True, exist_ok=True)
    zip_path = CACHE / Path(PYTHON_URL).name
    if not zip_path.exists():
        log(f"downloading {PYTHON_URL}")
        urllib.request.urlretrieve(PYTHON_URL, zip_path)
    sha = hashlib.sha256(zip_path.read_bytes()).hexdigest()
    if sha != PYTHON_SHA256:
        sys.exit(f"[build] {zip_path.name} has SHA-256 {sha}, not the pinned {PYTHON_SHA256}. If python.org's "
                 "published hash for this file agrees, update PYTHON_SHA256 in installer/build.py.")
    return sha


def write_buildinfo(sha: str, update_key: str) -> Path:
    path = BUILD / "BuildInfo.cs"
    path.write_text(
        "// Generated by installer/build.py\n"
        "namespace Keel\n{\n    static class BuildInfo\n    {\n"
        f'        public const string Version = "{VERSION}";\n'
        f'        public const string ReleasesRepo = "{RELEASES_REPO}";\n'
        f'        public const string UpdateKey = "{update_key}";  // the public key updates are signed with\n'
        f'        public const string PythonVersion = "{PYTHON_VERSION}";\n'
        f'        public const string PythonUrl = "{PYTHON_URL}";\n'
        f'        public const string PythonSha256 = "{sha}";\n'
        f'        public const string TorchIndex = "{TORCH_INDEX}";\n'
        f'        public const string NvidiaIndex = "{NVIDIA_INDEX}";\n'
        "    }\n}\n", encoding="utf-8")
    return path


# ---------------------------------------------------------------------------------------------------- icon
def icon_rgba(size: int) -> np.ndarray:
    """The app icon at one size, BGRA: a purple K up to 32 px, the full KEEL word from 40 px.
    Each size is a PNG in installer/icon, drawn from the Keel mark."""
    img = cv2.imread(str(HERE / "icon" / f"keel-{size}.png"), cv2.IMREAD_UNCHANGED)
    if img is None or img.shape != (size, size, 4):
        sys.exit(f"[build] installer/icon/keel-{size}.png is missing or not {size}x{size} RGBA")
    return img


def write_ico(path: Path, sizes=(16, 20, 24, 32, 40, 48, 64, 96, 128, 256)) -> None:
    """Multi-size .ico: 32-bit DIBs for the small sizes (every Windows API reads those), PNG for 256."""
    blobs = []
    for n in sizes:
        bgra = icon_rgba(n)
        if n >= 256:
            ok, png = cv2.imencode(".png", bgra)
            assert ok
            blobs.append((n, png.tobytes()))
            continue
        mask_row = ((n + 31) // 32) * 4
        header = struct.pack("<IiiHHIIiiII", 40, n, n * 2, 1, 32, 0, n * n * 4 + mask_row * n, 0, 0, 0, 0)
        pixels = bgra[::-1].tobytes()  # bottom-up rows
        blobs.append((n, header + pixels + bytes(mask_row * n)))
    out = struct.pack("<HHH", 0, 1, len(blobs))
    offset = 6 + 16 * len(blobs)
    for n, data in blobs:
        out += struct.pack("<BBBBHHII", n % 256, n % 256, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    path.write_bytes(out + b"".join(d for _, d in blobs))


# ---------------------------------------------------------------------------------------------------- compile
def csc() -> Path:
    for c in CSC_CANDIDATES:
        if c.exists():
            return c
    root = Path(r"C:\Program Files\Microsoft Visual Studio")
    if root.exists():
        found = sorted(root.glob("*/MSBuild/Current/Bin/Roslyn/csc.exe"))
        found += sorted(root.glob("*/*/MSBuild/Current/Bin/Roslyn/csc.exe"))
        if found:
            return found[-1]
    sys.exit("[build] no Roslyn csc.exe found; install Visual Studio Build Tools (the .NET desktop workload)")


def compile_exe(out: Path, sources: list[Path], icon: Path, resource: Path | None = None) -> None:
    args = [str(csc()), "/nologo", "/target:winexe", "/optimize+", "/langversion:7.3", "/platform:anycpu",
            f"/out:{out}", f"/win32icon:{icon}", f"/win32manifest:{HERE / 'launcher' / 'app.manifest'}"]
    args += [f"/reference:{r}" for r in REFS]
    args.append(f"/resource:{HERE / 'launcher' / 'Ui.xaml'},Ui.xaml")  # the window, loaded at run time
    if resource is not None:
        args.append(f"/resource:{resource},payload.zip")
    args += [str(s) for s in sources]
    res = subprocess.run(args, capture_output=True, text=True)
    if res.returncode != 0 or "warning" in res.stdout:
        print(res.stdout, res.stderr)
    if res.returncode != 0:
        sys.exit(f"[build] compiling {out.name} failed")
    log(f"{out.name}: {out.stat().st_size / 1e6:.1f} MB")


# ---------------------------------------------------------------------------------------------------- signing
def sign_tool() -> Path:
    """installer/tools/SignUpdate.exe, built with the launcher's own signature code."""
    out = BUILD / "SignUpdate.exe"
    args = [str(csc()), "/nologo", "/target:exe", "/optimize+", "/langversion:7.3", f"/out:{out}",
            str(HERE / "tools" / "SignUpdate.cs"), str(HERE / "launcher" / "UpdateSignature.cs")]
    res = subprocess.run(args, capture_output=True, text=True)
    if res.returncode != 0:
        print(res.stdout, res.stderr)
        sys.exit("[build] compiling the signing tool failed")
    return out


def update_key(tool: Path) -> str:
    """The public key updates are checked against (made, with its private half, on the first build)."""
    res = subprocess.run([str(tool), "key", str(SIGNING_KEY)], capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"[build] reading the update signing key failed: {res.stderr.strip()}")
    if res.stderr.strip():
        log(f"{res.stderr.strip()}. Back it up: installed copies only take updates signed with it")
    key = res.stdout.strip()
    if not key.startswith("<RSAKeyValue>") or '"' in key:
        sys.exit("[build] the update signing key doesn't look right")
    return key


def sign(tool: Path, setup: Path) -> None:
    res = subprocess.run([str(tool), "sign", str(SIGNING_KEY), str(setup), VERSION], capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"[build] signing {setup.name} failed: {res.stderr.strip()}")
    log(f"{setup.name}.sig: signed as {VERSION}; upload it to the release with the setup")


# ---------------------------------------------------------------------------------------------------- payload
def ignore_pycache(_dir: str, names: list[str]) -> list[str]:
    return [n for n in names if n == "__pycache__" or n.endswith((".pyc", ".pyo"))]


def stage_payload(stage: Path, launcher: Path, chiaki_build: Path | None, chiaki_src: Path | None) -> None:
    if stage.exists():
        shutil.rmtree(stage)
    app = stage / "app"
    app.mkdir(parents=True)
    shutil.copy2(ROOT / "run.py", app)
    shutil.copy2(ROOT / "keel.py", app)
    shutil.copytree(ROOT / "framegen", app / "framegen", ignore=ignore_pycache)
    (app / "models").mkdir()
    model = ROOT / "models" / MODEL
    if model.exists():
        shutil.copy2(model, app / "models")
    shutil.copy2(HERE / "requirements-runtime.txt", app)
    shutil.copy2(ROOT / "LICENSE", stage / "LICENSE.txt")
    shutil.copy2(HERE / "THIRD_PARTY_NOTICES.txt", stage)
    shutil.copy2(launcher, stage / "Keel.exe")

    if chiaki_build is None or chiaki_src is None:
        return
    # chiaki-ng: the deployed build, its licences and the source of our patch (AGPL: corresponding source).
    chiaki = stage / "chiaki"
    shutil.copytree(chiaki_build, chiaki)
    shutil.copy2(chiaki_src / "COPYING", chiaki / "LICENSE-AGPL-3.0.txt")
    lic = chiaki / "licenses"
    lic.mkdir()
    for f in (chiaki_src / "LICENSES").glob("*"):
        shutil.copy2(f, lic)
    ffmpeg = next(chiaki_src.glob("ffmpeg-*-win64-gpl-shared-*"), None)
    if ffmpeg is not None and (ffmpeg / "LICENSE.txt").exists():
        shutil.copy2(ffmpeg / "LICENSE.txt", lic / "FFmpeg-LICENSE.txt")
    src = chiaki / "source"
    src.mkdir()
    # The tap's own files as they were built (from the chiaki-ng source, so they always match the binary), then
    # how they're applied and built.
    for folder in ("src", "include"):
        for f in sorted((chiaki_src / "gui" / folder).glob("frametap*")):
            shutil.copy2(f, src)
    for name in ("apply_patch.py", "build_windows.sh", "README.md"):
        shutil.copy2(ROOT / "chiaki_tap" / name, src)
    diff = subprocess.run(["git", "-C", str(chiaki_src), "diff"], capture_output=True, text=True, check=True).stdout
    (src / "chiaki-ng-v1.10.1-frametap.patch").write_text(diff, encoding="utf-8")
    tag = subprocess.run(["git", "-C", str(chiaki_src), "describe", "--tags"], capture_output=True, text=True).stdout.strip()
    (src / "SOURCE.txt").write_text(
        f"This chiaki-ng is upstream {tag or 'v1.10.1'} (https://github.com/streetpea/chiaki-ng) with Keel's frame "
        "tap added:\n  frametap*.c, .cpp, .h              the tap (copied into gui/src and gui/include)\n"
        "  chiaki-ng-v1.10.1-frametap.patch  the changes to chiaki-ng's own files (git diff)\n"
        "  apply_patch.py, build_windows.sh  how it's applied and built (mirrors chiaki-ng's Windows CI)\n"
        "With the tap built in, chiaki-ng behaves exactly as before unless CHIAKI_FRAMETAP=1 is set.\n"
        "FFmpeg is the gpl-shared build from https://github.com/streetpea/FFmpeg-Builds (its source and build "
        "scripts are there).\n", encoding="utf-8")


def zip_dir(src: Path, out: Path) -> None:
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in sorted(src.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(src).as_posix())
    log(f"payload: {sum(f.stat().st_size for f in src.rglob('*') if f.is_file()) / 1e6:.0f} MB, "
        f"zipped {out.stat().st_size / 1e6:.0f} MB")


# The window used to be the old gold mark. These are the Keel purple (docs/brand/keel-icon.svg).
# Six-digit form so a translucent #55FFB02E becomes #55C4B5FD too. #1A1206 is the ink on the old gold buttons.
_GOLD = (
    ("FFBD24", "C4B5FD"),
    ("FC930B", "8B6CFF"),
    ("FC5F03", "5B3FD6"),
    ("FFCB5C", "C4B5FD"),
    ("FF8A1F", "5B3FD6"),
    ("FF9F2E", "8B6CFF"),
    ("FFB02E", "C4B5FD"),
    ("#1A1206", "#FFFFFF"),
)
_KEEL_MARK = """                  <!-- the logo (docs/brand/keel-icon.svg): the Keel wordmark -->
                  <Rectangle Width="1024" Height="1024" RadiusX="228" RadiusY="228">
                    <Rectangle.Fill><LinearGradientBrush StartPoint="0,0" EndPoint="1,1"><GradientStop Offset="0" Color="#C4B5FD"/><GradientStop Offset="0.45" Color="#8B6CFF"/><GradientStop Offset="1" Color="#5B3FD6"/></LinearGradientBrush></Rectangle.Fill>
                  </Rectangle>
                  <Path Fill="#FFFFFF" Data="M108 402H154V602H108Z M154 488L276 402H322L200 502L322 602H276L154 516Z M366 402H522V444H412V480H494V522H412V560H522V602H366Z M566 402H722V444H612V480H694V522H612V560H722V602H566Z M766 402H812V560H916V602H766Z"/>"""


def rebrand_text(text: str) -> str:
    """Swap the old gold mark for the purple Keel wordmark. Safe to run twice."""
    text = re.sub(
        r"<!-- the logo \(docs/brand/keel-icon\.svg\): the Keel wordmark -->.*?"
        r"<Path Fill=\"#(?:FFB02E|C4B5FD)\" Data=\"M540\.5.*?\"/>\s*"
        r"<Path Fill=\"#(?:1A1206|FFFFFF)\" Data=\"M540\.5.*?\"/>",
        _KEEL_MARK,
        text,
        count=1,
        flags=re.S,
    )
    for old, new in _GOLD:
        text = text.replace(old, new)
    return text


def rebrand_launcher() -> None:
    """The window source still carries the old gold in some checkouts. Rewrite it before compiling."""
    for name in ("Ui.xaml", "Ui.cs", "SettingsPage.cs"):
        path = HERE / "launcher" / name
        text = path.read_text(encoding="utf-8")
        branded = rebrand_text(text)
        if branded != text:
            path.write_text(branded, encoding="utf-8")
            log(f"recolored {name} to the Keel purple")


def main() -> int:
    global VERSION
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--launcher-only", action="store_true", help="build only Keel.exe")
    ap.add_argument("--app-setup", action="store_true",
                    help="build Keel-Setup.exe without embedding chiaki-ng; the installer uses the copy already on the PC")
    ap.add_argument("--version", default=VERSION, help=f"the version to build (default {VERSION}), e.g. 0.2.0-beta.1")
    ap.add_argument("--chiaki-build", type=Path, default=os.environ.get("KEEL_CHIAKI_BUILD"),
                    help="the patched chiaki-ng build folder (chiaki_tap/build_windows.sh output); "
                         "default: KEEL_CHIAKI_BUILD")
    ap.add_argument("--chiaki-src", type=Path, default=os.environ.get("KEEL_CHIAKI_SRC"),
                    help="the chiaki-ng source checkout it was built from; default: KEEL_CHIAKI_SRC")
    a = ap.parse_args()
    if not re.fullmatch(r"\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?", a.version):
        sys.exit(f"[build] {a.version} isn't a version like 0.2.0 or 0.2.0-beta.1")
    VERSION = a.version
    rebrand_launcher()

    BUILD.mkdir(parents=True, exist_ok=True)
    DIST.mkdir(parents=True, exist_ok=True)
    tool = sign_tool()
    sources = sorted((HERE / "launcher").glob("*.cs")) + [write_buildinfo(python_sha256(), update_key(tool))]
    icon = BUILD / "keel.ico"
    write_ico(icon)
    cv2.imwrite(str(BUILD / "icon-256.png"), icon_rgba(256))
    launcher = DIST / "Keel.exe"
    compile_exe(launcher, sources, icon)
    if a.launcher_only:
        return 0
    stage = BUILD / "stage"
    if a.app_setup:
        stage_payload(stage, launcher, None, None)
    else:
        if a.chiaki_build is None or a.chiaki_src is None:
            sys.exit("[build] say where chiaki-ng is: --chiaki-build and --chiaki-src, or set KEEL_CHIAKI_BUILD "
                     "and KEEL_CHIAKI_SRC")
        for p, what in ((a.chiaki_build / "chiaki.exe", "chiaki-ng build"), (a.chiaki_src / "COPYING", "chiaki-ng source")):
            if not p.exists():
                sys.exit(f"[build] {what} not found ({p})")
        stage_payload(stage, launcher, a.chiaki_build, a.chiaki_src)
    payload = BUILD / "payload.zip"
    zip_dir(stage, payload)
    compile_exe(DIST / "Keel-Setup.exe", sources, icon, resource=payload)
    sign(tool, DIST / "Keel-Setup.exe")
    return 0


if __name__ == "__main__":
    sys.exit(main())
